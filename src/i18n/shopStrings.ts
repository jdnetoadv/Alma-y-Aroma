/** Traduz uma chave do comércio, com interpolação simples de {variáveis}. */
export function shopT(locale: Locale, key: string, vars?: Record<string, string>): string {
  let text = shopStrings[locale][key] ?? shopStrings['pt-br'][key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value)
    }
  }
  return text
}
